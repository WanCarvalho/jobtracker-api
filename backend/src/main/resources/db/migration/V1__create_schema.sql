CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  normalized_name VARCHAR(180) NOT NULL,
  cnpj VARCHAR(18),
  website VARCHAR(255),
  description TEXT,
  approval_status VARCHAR(20) NOT NULL,
  created_by BIGINT NOT NULL REFERENCES users(id),
  reviewed_by BIGINT REFERENCES users(id),
  reviewed_at TIMESTAMP,
  review_notes VARCHAR(1000),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_companies_status ON companies(approval_status);
CREATE INDEX idx_companies_normalized_name ON companies(normalized_name);
CREATE TABLE application_stages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  name VARCHAR(100) NOT NULL,
  position INTEGER NOT NULL,
  color VARCHAR(20) NOT NULL,
  is_final BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_stage_user_name UNIQUE(user_id, name)
);
CREATE TABLE job_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  company_id BIGINT NOT NULL REFERENCES companies(id),
  stage_id BIGINT NOT NULL REFERENCES application_stages(id),
  job_title VARCHAR(180) NOT NULL,
  salary NUMERIC(12,2),
  job_url VARCHAR(1000),
  description TEXT,
  applied_at DATE NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_app_user ON job_applications(user_id);
CREATE INDEX idx_app_stage ON job_applications(stage_id);
CREATE TABLE application_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL REFERENCES job_applications(id),
  previous_stage_id BIGINT REFERENCES application_stages(id),
  new_stage_id BIGINT NOT NULL REFERENCES application_stages(id),
  changed_by BIGINT NOT NULL REFERENCES users(id),
  notes VARCHAR(1000),
  changed_at TIMESTAMP NOT NULL
);
CREATE TABLE application_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL REFERENCES job_applications(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  content TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL
);
